-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT fld.ID AS ENTITY_ID, fld.NAME AS ENTITY_NAME,
       fld.REGION, fld.CATEGORY, fld.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(o.CROP_STRESS_COUNT) AS CROP_STRESS_COUNT,
       SUM(o.OPERATING_HOURS) AS OPERATING_HOURS, SUM(o.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(o.DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(o.SCOUTING_DUE) AS SCOUTING_DUE, SUM(o.SCOUTING_DONE) AS SCOUTING_DONE,
       SUM(o.HARVEST_TONNES) AS HARVEST_TONNES, SUM(o.FERTILIZER_KG) AS FERTILIZER_KG,
       SUM(o.HEALTHY_PLANTS) AS HEALTHY_PLANTS, SUM(o.PLANTS_SCOUTED) AS PLANTS_SCOUTED,
       SUM(o.PEST_ALERTS) AS PEST_ALERTS,
       100.0 * SUM(o.HEALTHY_PLANTS) / NULLIF(SUM(o.PLANTS_SCOUTED), 0) AS HEALTH_PCT,
       SUM(o.FERTILIZER_KG) / NULLIF(SUM(o.HARVEST_TONNES), 0) AS FERT_KG_PER_T,
       100.0 * SUM(o.OPERATING_HOURS) / NULLIF(SUM(o.PLANNED_HOURS), 0) AS SENSOR_UPTIME_PCT,
       100.0 * SUM(o.SCOUTING_DONE) / NULLIF(SUM(o.SCOUTING_DUE), 0) AS SCOUTING_COMPLETION_PCT,
       MAX(o.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.FIELD_DAILY o
JOIN RAW.FIELDS fld ON fld.ID = o.ENTITY_ID
GROUP BY fld.ID, fld.NAME, fld.REGION, fld.CATEGORY, fld.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(HEALTHY_PLANTS) AS HEALTHY_PLANTS, SUM(PLANTS_SCOUTED) AS PLANTS_SCOUTED,
       SUM(HARVEST_TONNES) AS HARVEST_TONNES, SUM(FERTILIZER_KG) AS FERTILIZER_KG,
       SUM(PEST_ALERTS) AS PEST_ALERTS, SUM(CROP_STRESS_COUNT) AS CROP_STRESS_COUNT,
       100.0 * SUM(HEALTHY_PLANTS) / NULLIF(SUM(PLANTS_SCOUTED), 0) AS HEALTH_PCT,
       SUM(FERTILIZER_KG) / NULLIF(SUM(HARVEST_TONNES), 0) AS FERT_KG_PER_T
FROM RAW.FIELD_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.CROP_STRESS_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(CROP_STRESS_COUNT) AS CROP_STRESS_COUNT,
       SUM(DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(PLANTS_SCOUTED) - SUM(HEALTHY_PLANTS) AS STRESSED_PLANTS
FROM RAW.FIELD_DAILY
WHERE CROP_STRESS_COUNT > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(HEALTHY_PLANTS) AS HEALTHY_PLANTS, SUM(PLANTS_SCOUTED) AS PLANTS_SCOUTED,
         SUM(HARVEST_TONNES) AS HARVEST_TONNES, SUM(FERTILIZER_KG) AS FERTILIZER_KG,
         SUM(PEST_ALERTS) AS PEST_ALERTS, SUM(CROP_STRESS_COUNT) AS CROP_STRESSES,
         SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.FIELD_DAILY
), fields AS (SELECT COUNT(*) AS FIELD_COUNT FROM RAW.FIELDS),
coverage AS (
  SELECT 100.0 * SUM(LEAST(MAPPED_HA, FIELD_HA)) / NULLIF(SUM(FIELD_HA), 0) AS MAPPED_PCT
  FROM RAW.SENSOR_COVERAGE
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Plant Health Rate' AS TITLE,
         100.0 * HEALTHY_PLANTS / NULLIF(PLANTS_SCOUTED, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Crop-Stress Events', CROP_STRESSES, '' FROM observations
  UNION ALL SELECT 3, 'Fertilizer Intensity', FERTILIZER_KG / NULLIF(HARVEST_TONNES, 0), ' kg/t harvested' FROM observations
  UNION ALL SELECT 4, 'Crop Harvested (t)', HARVEST_TONNES, '' FROM observations
  UNION ALL SELECT 5, 'Sensor Network Uptime', 100.0 * OPERATING_HOURS / NULLIF(PLANNED_HOURS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Fields Monitored', FIELD_COUNT, '' FROM fields
  UNION ALL SELECT 7, 'Sensor Mapping Coverage', MAPPED_PCT, '%' FROM coverage
  UNION ALL SELECT 8, 'Pest Alerts', PEST_ALERTS, '' FROM observations
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '999,990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.CROP_STRESS_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
