-- Crop-stress risk scoring and crop harvest forecast over the synthetic snapshot.
-- Predicts P(crop-stress event in the next 7 days) per field and reports
-- out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.CROP_STRESS_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, t.CATEGORY, t.YEARS_CROPPED,
       r.MOISTURE_DEFICIT_MM, r.CANAL_LEVEL_PCT,
       AVG(r.MOISTURE_DEFICIT_MM) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS MOISTURE_DEFICIT_7D,
       SUM(r.CROP_STRESS_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS CROP_STRESSES_30D,
       IFF(SUM(r.CROP_STRESS_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'CROP_STRESS', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.FIELD_DAILY r JOIN RAW.FIELDS t ON t.ID = r.ENTITY_ID
-- Regional weather events are not field-driven, so they are excluded from training.
WHERE r.ROOT_CAUSE NOT IN ('Prolonged dry spell', 'River flooding') OR r.CROP_STRESS_COUNT = 0;

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.CROP_STRESS_TRAIN AS
SELECT CATEGORY, YEARS_CROPPED, MOISTURE_DEFICIT_MM, CANAL_LEVEL_PCT, MOISTURE_DEFICIT_7D, CROP_STRESSES_30D, LABEL
FROM ML.CROP_STRESS_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.CROP_STRESS_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, YEARS_CROPPED, MOISTURE_DEFICIT_MM, CANAL_LEVEL_PCT, MOISTURE_DEFICIT_7D, CROP_STRESSES_30D, LABEL
FROM ML.CROP_STRESS_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.CROP_STRESS_RISK_MODEL(
  INPUT_DATA => TABLE(ML.CROP_STRESS_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.CROP_STRESS_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.CROP_STRESS_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'YEARS_CROPPED', YEARS_CROPPED, 'MOISTURE_DEFICIT_MM', MOISTURE_DEFICIT_MM,
           'CANAL_LEVEL_PCT', CANAL_LEVEL_PCT, 'MOISTURE_DEFICIT_7D', MOISTURE_DEFICIT_7D, 'CROP_STRESSES_30D', CROP_STRESSES_30D)):probability:CROP_STRESS::FLOAT AS P
  FROM ML.CROP_STRESS_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'CROP_STRESS', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'CROP_STRESS', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'CROP_STRESS', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'CROP_STRESS', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per field (label unknown, so excluded from features).
CREATE TABLE ML.CROP_STRESS_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.CROP_STRESS_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.CROP_STRESS_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'YEARS_CROPPED', YEARS_CROPPED, 'MOISTURE_DEFICIT_MM', MOISTURE_DEFICIT_MM,
           'CANAL_LEVEL_PCT', CANAL_LEVEL_PCT, 'MOISTURE_DEFICIT_7D', MOISTURE_DEFICIT_7D, 'CROP_STRESSES_30D', CROP_STRESSES_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:CROP_STRESS::FLOAT, 4) AS CROP_STRESS_PROB_7D,
       CASE WHEN P:probability:CROP_STRESS::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:CROP_STRESS::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Grower-wide daily crop harvest forecast (14 days, tonnes) from the daily series.
CREATE VIEW ML.DAILY_HARVEST AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(HARVEST_TONNES)::FLOAT AS HARVEST_TONNES
FROM RAW.FIELD_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.HARVEST_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_HARVEST),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'HARVEST_TONNES'
);

CREATE TABLE ML.HARVEST_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, ROUND(FORECAST, 1) AS HARVEST_TONNES,
       ROUND(GREATEST(0, LOWER_BOUND), 1) AS LOWER_BOUND, ROUND(UPPER_BOUND, 1) AS UPPER_BOUND
FROM TABLE(ML.HARVEST_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
